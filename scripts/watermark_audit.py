#!/usr/bin/env python3
"""
GITU Section 8: AI Watermark and Unwanted Agent Branding Audit
Detects and optionally strips self-introduced AI development tool branding
(e.g., "Created by Gemini", "Generated by OpenCode", "Powered by Kilo Code",
"Built with Claude", Co-Authored-By trailers) while strictly preserving
third-party copyright notices, licenses, and functional code comments.
"""

import argparse
import json
import os
import re
from pathlib import Path

IGNORE_DIRS = {".git", "node_modules", "venv", ".venv", "__pycache__", "dist", "build", "target"}

TEXT_EXTENSIONS = {
    ".md", ".txt", ".rst", ".html", ".htm", ".css", ".js", ".jsx", ".ts", ".tsx",
    ".py", ".rs", ".go", ".swift", ".c", ".cpp", ".h", ".java", ".kt", ".sh", ".yml", ".yaml", ".toml"
}

BRANDING_PATTERNS = [
    ("AI Generator Credit Banner", re.compile(r"(?i)^\s*(?:<!--|#|//|/\*)?\s*(?:created|generated|built|powered|authored|scaffolded)\s+(?:by|with)\s+(?:google\s+)?(?:gemini|claude(?:\s+code)?|opencode|kilo\s*code|qwen(?:\s+code)?|cursor|windsurf|github\s+copilot|chatgpt|openai\s+codex)[^\n]*?(?:-->|\*/)?\s*$")),
    ("AI Co-Author Trailer", re.compile(r"(?i)^\s*Co-Authored-By:\s*(?:Claude|Gemini|OpenCode|Kilo\s*Code|Qwen|Cursor|GitHub\s+Copilot)\b[^\n]*$")),
    ("AI Promotional Footer", re.compile(r"(?i)^\s*>?\s*🤖?\s*Generated\s+with\s+\[?(?:Claude\s+Code|Gemini\s+CLI|OpenCode|Kilo\s+Code|Qwen\s+Code)\]?[^\n]*$")),
]

PROTECTED_LEGAL_KEYWORDS = ("copyright", "spdx-license-identifier", "licensed under", "mit license", "apache license", "all rights reserved")


def is_protected_legal_line(line: str) -> bool:
    low = line.lower()
    return any(k in low for k in PROTECTED_LEGAL_KEYWORDS)


def scan_and_clean_project(root: Path, apply_fixes: bool = False):
    root = root.resolve()
    findings = []
    cleaned_files = []

    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in IGNORE_DIRS]
        for fname in filenames:
            fpath = Path(dirpath) / fname
            if fpath.suffix.lower() not in TEXT_EXTENSIONS:
                continue
            rel = str(fpath.relative_to(root))
            try:
                lines = fpath.read_text(encoding="utf-8", errors="ignore").splitlines(keepends=True)
            except Exception:
                continue

            new_lines = []
            modified = False
            for idx, line in enumerate(lines, start=1):
                if is_protected_legal_line(line):
                    new_lines.append(line)
                    continue

                matched_rule = None
                for rule_name, pattern in BRANDING_PATTERNS:
                    if pattern.search(line.rstrip("\r\n")):
                        matched_rule = rule_name
                        break

                if matched_rule:
                    findings.append({
                        "file": rel,
                        "line": idx,
                        "rule": matched_rule,
                        "content": line.strip()[:160],
                        "action": "removed" if apply_fixes else "flagged",
                    })
                    if apply_fixes:
                        modified = True
                        continue
                new_lines.append(line)

            if apply_fixes and modified:
                fpath.write_text("".join(new_lines), encoding="utf-8")
                cleaned_files.append(rel)

    return {
        "project_root": str(root),
        "mode": "apply" if apply_fixes else "dry-run",
        "watermarks_found": len(findings),
        "files_cleaned": cleaned_files,
        "findings": findings,
        "policy_compliance": {
            "third_party_copyrights_preserved": True,
            "false_human_claims_added": False,
        },
    }


def main():
    parser = argparse.ArgumentParser(description="GITU Section 8: AI Watermark & Agent Branding Auditor")
    parser.add_argument("project_path", help="Path to local software project")
    parser.add_argument("--apply", action="store_true", help="Safely remove detected self-promotional AI watermarks")
    parser.add_argument("--output", help="Write JSON audit record to file path")
    args = parser.parse_args()

    report = scan_and_clean_project(Path(args.project_path), apply_fixes=args.apply)
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
