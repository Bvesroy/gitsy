#!/usr/bin/env python3
"""gitup branding_scan.py - find development-agent branding and AI boilerplate.

The goal is the project's own identity, not a claim about who wrote it. So this
scanner separates three things, and only the first is ever auto-removable:

  branding   - self-introduced promotional text: "Generated by <agent>",
               "Powered by <tool>", agent signature lines in comments/headers.
  boilerplate- generic filler left by generators: "This project was scaffolded
               by ...", an agent's banner comment, leftover TODO(agent) markers.
  protected  - anything that must stay: third-party copyright headers, SPDX /
               license blocks, dependency licenses, attribution files, and
               explanatory comments that happen to mention an AI tool.

Hard rules baked into the code:
  * never touch LICENSE / NOTICE / AUTHORS / COPYING / vendored trees;
  * never strip a comment that sits in a file with an SPDX or copyright header
    unless the matched line is itself agent-branding (an authorship claim);
  * never invent a provenance claim. The report records what was found; it does
    not assert "human-written" anywhere;
  * binaries are only reported, never rewritten.

Usage:
  python3 branding_scan.py --project ~/Developer/MyProject [--out branding.json]
                           [--json-only]
"""

from __future__ import annotations

import _bootstrap  # noqa: F401
import argparse
import re
import sys
from pathlib import Path

from gitup_common import (
    Finding,
    die,
    emit,
    looks_binary,
    sort_findings,
    parser,
    read_text,
    rel,
    summarize,
    walk,
)

# Agents and generators whose names show up in residue.
AGENTS = [
    "claude", "claude code", "anthropic claude", "chatgpt", "openai", "gpt-4",
    "gpt-5", "copilot", "github copilot", "gemini", "gemini cli", "bard",
    "opencode", "cursor", "windsurf", "codeium", "kilo code", "kilocode",
    "cline", "aider", "replit", "devin", "bolt.new", "lovable", "v0.dev",
    "warp", "tabnine", "supermaven", "continue.dev", "sourcegraph cody",
    "qwen code", "roo code", "zed ai", "junie", "jules", "codex",
]
AGENT_ALT = "|".join(re.escape(a) for a in sorted(AGENTS, key=len, reverse=True))

BRANDING_PATTERNS = [
    ("branding.generated-by", "medium",
     re.compile(rf"(?i)\b(?:generated|created|written|built|made|authored|produced|scaffolded|"
                rf"synthesized|powered)\s+(?:by|with|using)\s+(?:{AGENT_ALT})\b"),
     "Promotional provenance line left by a development agent."),
    ("branding.agent-signature", "medium",
     re.compile(rf"(?i)^[\s/*#\-<]*(?:{AGENT_ALT})[\s\-_/]*(?:signature|assistant|agent|bot)?[\s*/>]*$"),
     "Standalone signature line naming the development agent."),
    ("branding.agent-hashtag", "low",
     re.compile(rf"(?i)#(?:ai[_-]?generated|generated[_-]?by[_-]?\w+|{AGENT_ALT.replace(chr(92)+' ', '_')})"),
     "AI/agent hashtag or tag in a source header."),
    ("branding.agent-emoji", "low",
     re.compile(r"(?i)(?:🤖|✨\s*(?:ai|generated|assisted)|🚀\s*(?:generated|built) by)"),
     "Decorative AI marker in text content."),
    ("boilerplate.agent-banner", "low",
     re.compile(rf"(?i)\b(?:this (?:file|code|project|repository|readme) was "
                rf"(?:auto(?:matically)?[- ]?)?(?:generated|created|written|produced|scaffolded))"),
     "Generated-by banner in documentation or source."),
    ("boilerplate.todo-agent", "low",
     re.compile(rf"(?i)\bTODO\((?:{AGENT_ALT}|ai)\)"),
     "Agent-specific TODO marker."),
    ("boilerplate.ai-disclaimer", "info",
     re.compile(r"(?i)\b(?:as an ai language model|i cannot browse|i don't have access to real-?time)"),
     "Assistant boilerplate pasted into the project."),
]

# Protective signals: if a file carries these, findings stay advisory.
PROTECT_RE = re.compile(
    r"(?i)(?:SPDX-License-Identifier|Copyright\s+(?:\(c\)|©)?\s*\d{4}|"
    r"Licensed under the|All rights reserved|Apache License|MIT License|"
    r"GNU (?:General|Lesser) Public License)")
PROTECTED_NAMES = re.compile(
    r"(?i)^(?:LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE|AUTHORS|CONTRIBUTORS|"
    r"PATENTS|THIRD[-_]PARTY[-_]NOTICES?|ATTRIBUTION)(?:\..*)?$")
PROTECTED_DIRS = {"node_modules", "vendor", "third_party", "third-party",
                  "external", "deps", "Pods", "site-packages", ".venv", "venv"}

GENERATED_MARKER = re.compile(
    r"(?i)(?:@generated|do not edit|auto-?generated|this file is generated|"
    r"code generated by|automatically generated)")

# Files where agent branding is documentation-of-a-feature, not residue.
SELF_REFERENTIAL = re.compile(r"(?i)(?:skill\.md|agents?\.md|claude\.md|\.github/.*|"
                              r"prompt|system-prompt)")


def scan_branding(root: Path, max_hits: int = 300) -> dict:
    findings: list[Finding] = []
    protected_hits: list[dict] = []
    binary_assets: list[str] = []
    scanned = 0

    for path in walk(root):
        rp = rel(root, path)
        if any(part in PROTECTED_DIRS for part in Path(rp).parts):
            continue
        if PROTECTED_NAMES.match(path.name):
            continue
        if SELF_REFERENTIAL.search(rp) and path.suffix.lower() in (".md", ".mdc"):
            # The file documents agent behaviour; its own wording is content.
            continue
        if looks_binary(path):
            if path.suffix.lower() in (".png", ".jpg", ".jpeg", ".gif", ".webp",
                                       ".icns", ".ico", ".pdf", ".mp4"):
                # Watermarks in images cannot be judged from bytes; report for
                # a human look instead of pretending we detected something.
                try:
                    if path.stat().st_size > 512 * 1024:
                        binary_assets.append(rp)
                except OSError:
                    pass
            continue
        text = read_text(path)
        if not text or len(findings) >= max_hits:
            continue
        scanned += 1
        has_protection = bool(PROTECT_RE.search(text))
        is_generated = bool(GENERATED_MARKER.search(text[:2000]))
        # In Markdown, a line inside a fenced block is a command, a config value
        # or example output. `ln -s ~/.agents/skills/gitup` names an agent because
        # it is a path; it is not a signature left by one.
        in_fence = False
        for lineno, line in enumerate(text.splitlines(), start=1):
            stripped = line.strip()
            if stripped.startswith(("```", "~~~")):
                in_fence = not in_fence
                continue
            if not stripped or in_fence:
                continue
            # A Markdown heading naming an agent is a section title - "### Claude
            # Code" documents an integration. A signature is body text, and it is
            # a signature because it is unheaded and unattended. In any other
            # file, "#" opens a comment, and a commented-in signature is exactly
            # what this check exists to find.
            if path.suffix.lower() in (".md", ".markdown", ".mdx", ".rst") \
                    and re.match(r"#{1,6}\s", stripped):
                continue
            for rule_id, sev, pattern, why in BRANDING_PATTERNS:
                if not pattern.search(stripped):
                    continue
                evidence = [f"{rp}:{lineno}"]
                # A line that also carries a copyright/SPDX notice is protected.
                if PROTECT_RE.search(stripped):
                    protected_hits.append({
                        "path": rp, "line": lineno, "rule": rule_id,
                        "why": "line carries a copyright or license notice",
                        "text": stripped[:160]})
                    continue
                if rule_id.startswith("boilerplate.") and is_generated:
                    # the file says it is generated; leave its banner alone,
                    # but record it so the maintainer can decide.
                    protected_hits.append({
                        "path": rp, "line": lineno, "rule": rule_id,
                        "why": "file declares itself generated",
                        "text": stripped[:160]})
                    continue
                findings.append(Finding(
                    checklist="presentation", id=rule_id, severity=sev,
                    title=f"{why} ({rp}:{lineno})",
                    detail=stripped[:200],
                    evidence=evidence,
                    fix="Delete the branding line; keep any technical explanation it was attached to."
                        if sev != "info" else "Optional cleanup; harmless if it is real documentation.",
                    # Compute the same protection rule used for protected_hits,
                    # so an autofixable finding can never live in a file (or on
                    # a line) that carries a copyright / license notice.
                    autofix="strip_line" if (
                        rule_id in ("branding.generated-by", "branding.agent-signature",
                                    "boilerplate.agent-banner", "boilerplate.todo-agent")
                        and not has_protection and not PROTECT_RE.search(stripped)) else ""))
                break

    findings = sort_findings(findings)
    return {
        "checklist": "presentation",
        "project": str(root),
        "files_scanned": scanned,
        "summary": summarize(findings),
        "branding_found": sum(1 for f in findings if f.id.startswith("branding.")),
        "boilerplate_found": sum(1 for f in findings if f.id.startswith("boilerplate.")),
        "findings": [f.as_dict() for f in findings],
        "protected_hits": protected_hits[:60],
        "images_to_review_manually": binary_assets[:20],
        "policy": [
            "Only self-introduced agent branding is removable.",
            "Copyright, SPDX, license and dependency attribution are never touched.",
            "No claim about how the project was written is added or removed.",
            "Report says what was found; it does not certify authorship.",
        ],
    }


def main(argv=None):
    ap = parser(description="gitup AI-branding residue scan")
    ap.add_argument("--project", required=True)
    ap.add_argument("--out", default="")
    args = ap.parse_args(argv)
    root = Path(args.project).expanduser().resolve()
    if not root.is_dir():
        die(f"project directory not found: {root}")
    emit(scan_branding(root), args.out or None)
    return 0


if __name__ == "__main__":
    sys.exit(main())
